import sbt._
import sbt.Keys._

/** Facade parity (SPEC 6.5): one app body, compiled once for each ecosystem.
  *
  * The generator copies a template (for example
  * `examples/src/parity/CounterBody.scala.txt`) once per entry of
  * [[FacadeParity.ecosystems]], with the package `parity.on<name>` and the
  * import line of that ecosystem, into the managed sources. It also writes
  * `parity.Parity.apps`, the list of the generated apps, for the tests. If the
  * body compiles under every import, the facades re-export the shared surface
  * unchanged.
  *
  * The ZIO and Cats Effect pull requests add their entry:
  * {{{
  * FacadeParity.ecosystems += "zio" -> "import tui4s.interop.zio.*"
  * }}}
  */
object FacadeParity {

  /** The ecosystems: a short name and the import line of its facade. */
  val ecosystems = settingKey[Seq[(String, String)]](
    "Short name and import line of each ecosystem for the facade parity check",
  )

  /** The template that the generator copies. */
  val template = settingKey[File]("The app body that every ecosystem compiles")

  /** The settings of a project that compiles the parity sources. */
  def settings(body: File): Seq[Setting[_]] = Seq(
    template   := body,
    ecosystems := Seq("kyo" -> "import tui4s.*"),
    Compile / sourceGenerators += Def.task {
      generate(
        template.value,
        (Compile / sourceManaged).value / "parity",
        ecosystems.value,
      )
    }.taskValue,
    // Changes in the template start the generator again.
    watchSources += WatchSource(body),
  )

  /** Writes one file per ecosystem and the list of apps; returns the files. */
  def generate(
      template: File,
      dir: File,
      ecosystems: Seq[(String, String)],
  ): Seq[File] = {
    val text  = IO.read(template)
    val apps  = ecosystems.map { case (name, importLine) =>
      val file = dir / s"on$name" / "CounterBody.scala"
      IO.write(
        file,
        text
          .replace("@PACKAGE@", s"parity.on$name")
          .replace("@IMPORT@", importLine),
      )
      file
    }
    val names = ecosystems
      .map { case (name, _) =>
        s"""    "$name" -> parity.on$name.CounterBody"""
      }
      .mkString(",\n")
    val list  = dir / "Parity.scala"
    IO.write(
      list,
      s"""package parity
         |
         |/** Generated by project/FacadeParity.scala: the parity apps. */
         |object Parity:
         |    val apps: Seq[(String, tui4s.App[Int])] = Seq(
         |$names,
         |    )
         |""".stripMargin,
    )
    apps :+ list
  }
}
