import com.typesafe.sbt.packager.archetypes.scripts.ScriptUtils
import sbt._

/** Keep package-named example commands while native-packager owns JVM
  * launchers.
  */
object ExamplePackaging {
  private def names(mains: Seq[String]): Map[String, String] = {
    val selected = mains.filter(_.startsWith("examples."))
    val packages = selected.map(main => main -> main.split('.').init.last)
    packages.groupBy(_._2).foreach { case (name, entries) =>
      if (entries.size > 1)
        sys.error(
          s"Example launchers: ${entries.map(_._1).mkString(", ")} get the same script name $name",
        )
    }
    val byMain   = packages.toMap
    ScriptUtils
      .createScriptNames(selected)
      .map { case (main, script) =>
        script -> byMain(main)
      }
      .toMap
  }

  /** Rename generated scripts in the distribution; omit its main-less
    * dispatcher.
    */
  def mappings[A](
      files: Seq[(A, String)],
      mains: Seq[String],
      dispatcher: String,
  ): Seq[(A, String)] = {
    val aliases = names(mains)
    files.flatMap { case (source, path) =>
      val suffix = if (path.endsWith(".bat")) ".bat" else ""
      val script = path.stripPrefix("bin/").stripSuffix(suffix)
      aliases.get(script).filter(_ => path.startsWith("bin/")) match {
        case Some(name)                                => Some(source -> s"bin/$name$suffix")
        case None if path == s"bin/$dispatcher$suffix" => None
        case None                                      => Some(source -> path)
      }
    }
  }

  /** Preserve the developer/PTY paths and forward every argument to the app. */
  def launchers(
      staged: File,
      target: File,
      classpath: Seq[String],
      mains: Seq[String],
  ): Seq[File] = {
    val bin = target / "bin"
    val cp  = classpath.map(name => (staged / "lib" / name).getAbsolutePath)
    IO.write(bin / "classpath", cp.mkString(java.io.File.pathSeparator))
    // Map.values.toSeq can be a lazy Stream in sbt's Scala 2.12. Materialize
    // names before writing files so every launcher is generated by this task.
    names(mains).values.toVector.sorted.map { name =>
      val launcher = staged / "bin" / name
      if (!launcher.isFile)
        sys.error(s"Packaged launcher is missing: $launcher")
      val relative = bin.toPath.toAbsolutePath
        .relativize(launcher.toPath.toAbsolutePath)
        .toString
        .replace(java.io.File.separatorChar, '/')
      val quoted   = "'" + relative.replace("'", "'\\''") + "'"
      val file     = bin / name
      IO.write(
        file,
        s"""#!/bin/sh
           |# Written by sbt examples/launchers; native-packager owns the JVM command.
           |exec "$$(dirname "$$0")"/$quoted -- "$$@"
           |""".stripMargin,
      )
      if (!file.setExecutable(true))
        sys.error(s"Cannot make launcher executable: $file")
      file
    }
  }
}
